#!/bin/sh
# إعادة حساب أسعار كل الكتب (دولار + ليرة سورية) دفعة واحدة، بعد تحديث
# سعر الصرف من شاشة الإعدادات (المكتبة ← الإعدادات).
#
# لماذا هذا ضروري: الأسعار المعروضة للزوار محسوبة ومخزَّنة وقت حفظ كل
# كتاب فقط (وليس محسوبة لحظياً عند كل زيارة) — قرار مقصود لتفادي حساب
# رياضي عند كل تحميل صفحة. لذلك بعد أي تعديل على سعر الصرف، يجب تشغيل
# هذا السكربت لتحديث كل الكتب المنشورة دفعة واحدة.
#
# التشغيل من مجلد repository/:
#   docker compose run --rm wpcli sh /scripts/recalculate-prices.sh

set -e

echo "== إعادة حساب أسعار كل الكتب بأسعار الصرف الحالية =="

wp eval '
$result = \Maktaba\Core\Admin\Pricing\PriceRecalculator::recalculateAll();
echo "تم تحديث: " . $result["updated"] . " كتاب\n";
echo "تم تجاوز (بلا سعر رسمي مُدخَل بعد): " . $result["skipped"] . " كتاب\n";
'

echo "== انتهى =="
